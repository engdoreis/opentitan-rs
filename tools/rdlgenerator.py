#!/usr/bin/env python

from pathlib import Path
import click
import json
import jinja2
import sys

@click.group()
def main() -> None:
    """Cli."""

def gen_from_template(input_file: Path, out_file: Path, template:str, comment_scape:str = "//") -> None:
    """Process a template an generate a file.
    """
    print(f"Loading file: {input_file}...")
    with input_file.open("r") as f:
        rdljson = json.load(f)
    
    template = jinja2.Template(template)

    with out_file.open("a") as f:
        f.write(template.render(rdljson))
    
    print(f"Successfully generated {out_file}")

def get_command_line() -> str:
    args = []
    for item in sys.argv:
        if Path(item).exists():
            args.append(str(Path(item).resolve().relative_to(Path.cwd())))
        else: 
            args.append(item)
    return " ".join(args)

LICENSE_HEADER = """ Copyright Douglas Reis
Licensed under the Apache License, Version 2.0, see LICENSE for details.
SPDX-License-Identifier: Apache-2.0
"""

LD_TEMPLATE = """
MEMORY
{
{%- for device in devices %}
  {%- set base_addr = device.offset if device.offset else device.offsets[0] %}
    {%- if device.type == "mem" %}
    {{"{:<10}: ORIGIN = {:#010x}, LENGTH = {:#08x} /*{:>6} KiB */".format(device.name, base_addr, device.size, device.size/1024)}}
    {%- endif %}
{%- endfor %}
}
"""
@main.command()
@click.argument(
    "input_file",
    type=click.Path(path_type=Path, writable=False),
)
@click.argument(
    "out_file",
    default="./build/memory.ld",
    type=click.Path(path_type=Path, writable=True),
)
def gen_linker_script(input_file: Path, out_file: Path) -> None:
    """Generate a linker file with the memory map.

    INPUT_FILE: A json file generated by rdl2ot
    OUT_FILE: The name of the file to be generated

    """

    cmd = get_command_line()
    with out_file.open("w") as f:
        f.write(f"/*{LICENSE_HEADER}*/\n")
        f.write(f"/* Auto-generated: `{cmd}` */")
    gen_from_template(input_file, out_file, LD_TEMPLATE)


if __name__ == "__main__":
    main()
